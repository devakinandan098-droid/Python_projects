import turtle as t
import random as r
t.speed(0)
t.bgcolor("black")
color=["red","blue","green","orange","sea green","sky blue","gray","white"]
def a(x,y):
    t.penup()
    t.setpos(x,y)
    t.pendown()
    t.pencolor("yellow")
    t.fillcolor("yellow")
    t.begin_fill()
    t.circle(50)
    t.end_fill()
    t.setpos(x-15,y+60)
    t.fillcolor("blue")
    t.begin_fill()
    t.circle(10)
    t.end_fill()
    t.setpos(x+15,y+60)
    t.begin_fill()
    t.circle(10)
    t.end_fill()
    t.setpos(x-25,y+40)
    t.pencolor("black")
    t.width(10)
    t.goto(x-10, y+20)
    t.goto(x+10,y+20)
    t.goto(x+25,y+40)
    t.width(1)
t.onscreenclick(a)
t.done()