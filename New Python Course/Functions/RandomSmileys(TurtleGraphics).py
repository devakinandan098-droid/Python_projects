import random as r
import turtle as t
t.speed(0)
t.bgcolor("black")
t.hideturtle()
def smiley_face(x,y):
    t.penup()
    t.setpos(x,y)
    t.pendown()
    t.pencolor("yellow")
    t.fillcolor("yellow")
    t.begin_fill()
    t.circle(50)
    t.end_fill()
    t.setpos(x-15,y+60)
    t.fillcolor("blue")
    t.begin_fill()
    t.circle(10)
    t.end_fill()
    t.setpos(x+15,y+60)
    t.begin_fill()
    t.circle(10)
    t.end_fill()
    t.setpos(x-25,y+40)
    t.pencolor("black")
    t.width(10)
    t.goto(x-10, y+20)
    t.goto(x+10,y+20)
    t.goto(x+25,y+40)
    t.width(1)
for n in range(50):
    x = r.randrange(-t.window_width()//2,
                    t.window_width()//2)
    y = r.randrange(-t.window_height()//2,
                    t.window_height()//2)
    smiley_face(x,y)
t.done()