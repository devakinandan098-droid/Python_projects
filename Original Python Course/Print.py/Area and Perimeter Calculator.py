s=int(input("Enter the value of side for square:"))
SquareArea=s*s
SquarePerimeter=4*s

print("Area of square:", SquareArea)
print("Perimeter of square is: ", SquarePerimeter)


l=int(input("Enter the value of side for Rectangle: "))
w=int(input("Enter Width: "))
