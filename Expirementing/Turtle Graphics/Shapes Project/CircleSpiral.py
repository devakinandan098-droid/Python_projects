import turtle as t
t.bgcolor("black")
t.speed(0)
position = t.position()
heading = t.heading()
color = ["red", "blue", "green"]
t.penup()
t.rt(90)
t.fd(200)
t.lt(90)
t.fd(100)
t.pendown()
for y in range(4):
    t.lt(1)
    for x in range(6):
        t.color(color[x%3])
        t.circle(100)
        t.penup()
        t.lt(60)
        t.fd(300)
        t.pendown()
        print(position, heading)
t.penup()
t.lt(180)
t.fd(100)
t.rt(80)
t.fd(300)
t.rt(90)
t.fd(-50)
t.pendown()
for x in range(4):
    t.pencolor("orange")
    t.fd(100)
    t.rt(90)
t.done()